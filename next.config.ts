import type { NextConfig } from "next";

/**
 * Baseline hardening. No CSP: the page relies on inline styles and a JSON-LD
 * script, and a wrong policy would break rendering more than it protects.
 */
const securityHeaders = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "SAMEORIGIN" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  {
    key: "Permissions-Policy",
    value: "camera=(), microphone=(), geolocation=(), payment=()",
  },
];

// A production build without an origin publishes localhost canonical URLs,
// OG images, JSON-LD and a localhost sitemap. Say so instead of shipping it
// silently.
if (
  process.env.NODE_ENV === "production" &&
  !process.env.NEXT_PUBLIC_SITE_URL &&
  !process.env.VERCEL_PROJECT_PRODUCTION_URL &&
  !process.env.VERCEL_URL
) {
  console.warn(
    "[bueta-portfolio] NEXT_PUBLIC_SITE_URL is not set — canonical URLs, OG metadata, JSON-LD and the sitemap will fall back to http://localhost:3000.",
  );
}

const nextConfig: NextConfig = {
  poweredByHeader: false,
  // Every raster asset ships as WebP generated by scripts/optimize-images.mjs,
  // so the build does not depend on a runtime image optimizer (portable to
  // Cloudflare Workers / static hosts). next/image is still used for explicit
  // dimensions, lazy loading and CLS-free layout.
  images: {
    unoptimized: true,
  },
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default nextConfig;
